#!/bin/bash
# Regenerate docs/TEST-PARITY.md: every reference test id (docs/test-parity/reference-ids.txt, from
# `pytest --collect-only -q` on main) → the Rust test(s) tagged `/// py: <id>`, or why it isn't ported yet
# (docs/test-parity/pending.txt, lines "<id> | <reason>").
set -euo pipefail
cd "$(dirname "$0")/.."
ids=docs/test-parity/reference-ids.txt
pending=docs/test-parity/pending.txt
out=docs/TEST-PARITY.md
tags=$(mktemp)
trap 'rm -f "$tags"' EXIT
# one line per tag: "<py id><TAB><file>:<line> <rust fn>"
find crates services sims harness -name '*.rs' -not -path '*/target/*' -print0 2>/dev/null |
  xargs -0 awk '
    FNR == 1 { want = 0 }
    /\/\/\/ py: / {
      s = $0; sub(/.*\/\/\/ py: /, "", s); sub(/ .*/, "", s)
      id = s; at = FILENAME ":" FNR; want = 1; next
    }
    want && /fn [A-Za-z0-9_]+/ {
      match($0, /fn [A-Za-z0-9_]+/); print id "\t" at " " substr($0, RSTART + 3, RLENGTH - 3); want = 0
    }' > "$tags"
total=$(grep -c . "$ids")
ported=0
rows=""
while IFS= read -r id; do
  hits=$(awk -F'\t' -v id="$id" '$1 == id { print "`" $2 "`" }' "$tags" | paste -sd ' ' -)
  if [ -n "$hits" ]; then
    ported=$((ported + 1))
    rows+="| \`$id\` | ported | $hits |"$'\n'
  else
    reason=""
    [ -f "$pending" ] && reason=$(awk -F' [|] ' -v id="$id" '$1 == id { print $2 }' "$pending")
    rows+="| \`$id\` | pending | ${reason:-not ported yet} |"$'\n'
  fi
done < "$ids"
{
  echo "# Test parity: the reference tests"
  echo
  echo "Generated by \`harness/test-parity.sh\` from the \`/// py: <pytest id>\` tags on the Rust tests; do not edit by"
  echo "hand. The reference ids are \`pytest --collect-only -q\` on \`main\` (\`docs/test-parity/reference-ids.txt\`)."
  echo
  echo "**$ported of $total ported.**"
  echo
  echo "| Reference test | State | Rust test(s) |"
  echo "|---|---|---|"
  printf '%s' "$rows"
} > "$out"
echo "$ported/$total ported -> $out"
