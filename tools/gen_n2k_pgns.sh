#!/bin/bash
# Regenerate crates/proto-n2k/src/pgns/tables.rs (fast-packet PGNs, PGN names, manufacturer and device-class names)
# from CANboat's canboat.json. Needs jq. Run from anywhere:
#
#   curl -sSfLo /tmp/canboat.json https://raw.githubusercontent.com/canboat/canboat/master/docs/canboat.json
#   tools/gen_n2k_pgns.sh /tmp/canboat.json
#
# Then `cargo test -p proto-n2k` (its table sizes are pinned: update them on purpose, with the diff in hand).
set -euo pipefail
JSON=${1:?usage: tools/gen_n2k_pgns.sh <canboat.json>}
OUT="$(cd "$(dirname "$0")/.." && pwd)/crates/proto-n2k/src/pgns/tables.rs"
# shellcheck disable=SC2016  # jq's $vars, not the shell's
jq -r '
  # Manufacturer-proprietary PGN ranges: canboat lists per-manufacturer variants; the first variant'"'"'s name (e.g.
  # "Seatalk: …") would mislabel every other maker'"'"'s traffic.
  def proprietary: . == 61184 or (. >= 65280 and . <= 65535) or . == 126720 or (. >= 130816 and . <= 131071);
  def rows: map("    (\(.k), \(.v | tojson)),") | join("\n");
  ([.PGNs[] | select(.Type == "Fast") | .PGN] | unique) as $fast
  # the first variant with a real description names the PGN
  | (reduce (.PGNs[] | select((.Description // "") as $s | $s != "" and ($s | startswith("0x") | not)
                              and ($s | startswith("Manufacturer Proprietary") | not))) as $p
       ({}; if has($p.PGN | tostring) then . else .[$p.PGN | tostring] = $p.Description end)
     | with_entries(if (.key | tonumber | proprietary) then .value = "Manufacturer proprietary" else . end)
     # 126208 has several canboat variants; name it for the whole group, not the first variant
     | .["126208"] = "NMEA Request/Command/Acknowledge group function"
     | to_entries | map({k: (.key | tonumber), v: .value}) | sort_by(.k)) as $names
  # a lookup value listed twice keeps its last name
  | ([.LookupEnumerations[] | {key: .Name, value: .EnumValues}] | from_entries) as $lk
  | def enum(n): $lk[n] | group_by(.Value) | map(last | {k: .Value, v: .Name});
  "//! Generated by tools/gen_n2k_pgns.sh from CANboat \(.Version) (canboat.json): do not edit.",
  "//!",
  "//! CANboat (C) 2009-2026 Kees Verruijt and contributors, https://github.com/canboat/canboat,",
  "//! licensed under the Apache License 2.0.",
  "//! Only PGN numbers, names and frame type are taken.",
  "",
  "/// PGNs CANboat marks as Type \"Fast\" (sorted).",
  "pub static FAST_PACKET_PGNS: &[u32] = &[",
  ([range(0; $fast | length; 14) as $i | "    " + ($fast[$i:$i + 14] | map(tostring) | join(", ")) + ","] | join("\n")),
  "];",
  "",
  "/// PGN → CANboat description (sorted by key).",
  "pub static PGN_NAMES: &[(u32, &str)] = &[",
  ($names | rows),
  "];",
  "",
  "/// NMEA 2000 manufacturer code → name (sorted by key).",
  "pub static MANUFACTURERS: &[(u16, &str)] = &[",
  (enum("MANUFACTURER_CODE") | rows),
  "];",
  "",
  "/// NMEA 2000 device class → name (sorted by key).",
  "pub static DEVICE_CLASSES: &[(u8, &str)] = &[",
  (enum("DEVICE_CLASS") | rows),
  "];"
' "$JSON" > "$OUT.new"
mv "$OUT.new" "$OUT"
echo "wrote $OUT"
